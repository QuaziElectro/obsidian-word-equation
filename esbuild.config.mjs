import esbuild from "esbuild";
import process from "process";
import fs from "fs";
import path from "path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "jsdom",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
  ],
  format: "cjs",
  target: "es2022",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
});

if (prod) {
  await context.rebuild();
  // Copy to test-vault
  const vaultPluginDir = path.join("test-vault", ".obsidian", "plugins", "obsidian-word-equation");
  if (fs.existsSync(vaultPluginDir)) {
    fs.copyFileSync("main.js", path.join(vaultPluginDir, "main.js"));
    if (fs.existsSync("manifest.json")) {
      fs.copyFileSync("manifest.json", path.join(vaultPluginDir, "manifest.json"));
    }
    if (fs.existsSync("styles.css")) {
      fs.copyFileSync("styles.css", path.join(vaultPluginDir, "styles.css"));
    }
  }
  process.exit(0);
} else {
  await context.watch();
}
